// Extracts the verbatim system prompt of the NEWEST version (LEARN_PROMPT.md section 2, the
// ````text fenced block - learn-v8.1) and writes it to prompts/learn-v8.1.txt and to
// src/prompts/learnV81.ts. Never retype the prompt by hand - LEARN_PROMPT.md is
// the single source of truth (see LEARN_PROMPT.md's own header). The older versions
// (prompts/learn-v7.txt, src/prompts/learnV7.ts; prompts/learn-v8.txt, learn-v8-noE1.txt,
// src/prompts/learnV8.ts) are frozen: they are kept for the eval's `--prompt` comparison and
// never written again. (Which version every learn sends is `promptVersion`, config/prompts.ts.)
//
// The eval variant learn-v8.1-noE1 (the prompt audit's arm B, docs/proposals/prompt-audit-learn-v7.md
// section 5) is learn-v8.1 without its one "E1" line - the step-2 bullet that says code completes the
// data parts of the rules from every row. It is made here, at build time, from the same block
// (prompts/learn-v8.1-noE1.txt and `LEARN_SYSTEM_PROMPT_V8_1_NO_E1`), so the two can never drift apart.
//
// Run after any change to that fenced block:
//   pnpm --filter @formatai/api exec tsx ../../packages/shared/scripts/sync-prompt.ts
//   (or: node --experimental-strip-types packages/shared/scripts/sync-prompt.ts)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..', '..');
const specPath = path.join(repoRoot, 'LEARN_PROMPT.md');

/** Extracts the ````text ... ```` fenced system prompt from LEARN_PROMPT.md's markdown. */
export function extractLearnPrompt(markdown: string): string {
  const normalized = markdown.replace(/\r\n/g, '\n');
  const match = normalized.match(/````text\n([\s\S]*?)\n````/);
  if (!match) {
    throw new Error('Could not find the ````text fenced system prompt in LEARN_PROMPT.md');
  }
  return `${match[1]}\n`;
}

/** How the E1 line starts (LEARN_PROMPT.md "How to work", step 2; the same since learn-v8): the whole line is what the noE1 variant leaves out. */
export const E1_LINE_START = '   - Code completes the data parts of your rules from every row of the example';

/** The prompt without its E1 line. Throws unless the prompt has exactly one such line (a reworded line must be renamed here too). */
export function withoutE1(prompt: string): string {
  const lines = prompt.split('\n');
  const at = lines.flatMap((line, i) => (line.startsWith(E1_LINE_START) ? [i] : []));
  if (at.length !== 1) {
    throw new Error(`Expected exactly one E1 line ("${E1_LINE_START.trim()} ...") in the prompt, found ${at.length}`);
  }
  lines.splice(at[0]!, 1);
  return lines.join('\n');
}

function main(): void {
  const markdown = readFileSync(specPath, 'utf8');
  const prompt = extractLearnPrompt(markdown);
  const noE1 = withoutE1(prompt);

  const txtPath = path.join(here, '..', 'prompts', 'learn-v8.1.txt');
  writeFileSync(txtPath, prompt, 'utf8');
  const noE1Path = path.join(here, '..', 'prompts', 'learn-v8.1-noE1.txt');
  writeFileSync(noE1Path, noE1, 'utf8');

  const tsPath = path.join(here, '..', 'src', 'prompts', 'learnV81.ts');
  const tsContent =
    '// Generated by scripts/sync-prompt.ts from LEARN_PROMPT.md. Do not edit by hand.\n' +
    `export const LEARN_SYSTEM_PROMPT_V8_1 = ${JSON.stringify(prompt)};\n` +
    '\n' +
    '// learn-v8.1 without its E1 line (the eval variant learn-v8.1-noE1; see scripts/sync-prompt.ts).\n' +
    `export const LEARN_SYSTEM_PROMPT_V8_1_NO_E1 = ${JSON.stringify(noE1)};\n`;
  writeFileSync(tsPath, tsContent, 'utf8');

  console.log(`Wrote ${txtPath}`);
  console.log(`Wrote ${noE1Path}`);
  console.log(`Wrote ${tsPath}`);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) main();
